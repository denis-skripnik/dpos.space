const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
(async () => {
  const sent = [];
  const transport = { postMessage(value) { sent.push(JSON.parse(value)); } };
  const c = { console, setTimeout, clearTimeout, DposAndroidTransport: transport, location: { origin: 'https://dpos.blinddev.xyz' } };
  c.window = c;
  vm.runInNewContext(fs.readFileSync('v3/js/native-bridge.js', 'utf8'), c);
  assert(c.DposNative.available());
  const first = c.DposNative.request('getAppInfo');
  const second = c.DposNative.request('getWorkerStatus');
  assert.strictEqual(sent[0].version, 2);
  assert.notStrictEqual(sent[0].id, sent[1].id);
  transport.onmessage({ data: JSON.stringify({ version: 2, id: sent[1].id, ok: true, result: { running: false } }) });
  transport.onmessage({ data: JSON.stringify({ version: 2, id: sent[0].id, ok: true, result: { bridgeVersion: 2 } }) });
  assert.strictEqual((await first).bridgeVersion, 2);
  assert.strictEqual((await second).running, false);
  const failed = c.DposNative.request('stopWorker');
  transport.onmessage({ data: JSON.stringify({ version: 2, id: sent[2].id, ok: false, error: { message: 'cancelled' } }) });
  await assert.rejects(failed, /cancelled/);
  const old = { window: null, DposAndroid: { startWorker() { throw new Error('must not call legacy'); } }, setTimeout, clearTimeout };
  old.window = old;
  vm.runInNewContext(fs.readFileSync('v3/js/native-bridge.js', 'utf8'), old);
  assert.strictEqual(old.DposNative.available(), false);
  assert.strictEqual(old.DposNative.needsUpdate(), true);
  await assert.rejects(old.DposNative.request('startWorker'), /обнов/i);
  const notifyContext = { window: null, console, setTimeout, clearTimeout, DposNative: c.DposNative, navigator: {}, location: { hash: '#' }, addEventListener() {} };
  notifyContext.window = notifyContext;
  vm.runInNewContext(fs.readFileSync('v3/js/pwa.js', 'utf8'), notifyContext);
  const notified = notifyContext.DposPwa.notify('Test', { body: 'safe' });
  assert.strictEqual(sent[3].method, 'notify');
  transport.onmessage({ data: JSON.stringify({ version: 2, id: sent[3].id, ok: true, result: { ok: true } }) });
  assert.strictEqual(await notified, true);
  console.log('v3 native async transport behavioral tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
