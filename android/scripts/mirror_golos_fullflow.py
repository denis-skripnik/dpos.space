#!/usr/bin/env python3
"""Host mirrors differ ONLY in runner import/annotation and AndroidTest class names.
--check detects drift; no production/source-set/build configuration changes.
"""
from pathlib import Path
import argparse
p=argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args=p.parse_args()
src=Path(__file__).resolve().parents[1]/'app/src'
files=sorted((src/'androidTest/java/space/dpos/android').glob('GolosFullFlow*.kt'))
for f in files:
    # Physical lifecycle gate has Android instrumentation args and cannot be a host test.
    if 'Lifecycle' in f.name: continue
    text=f.read_text().replace('import androidx.test.ext.junit.runners.AndroidJUnit4', 'import org.robolectric.RobolectricTestRunner').replace('AndroidJUnit4::class', 'RobolectricTestRunner::class').replace('AndroidTest', 'HostTest')
    dest=src/'test/java/space/dpos/android'/f.name.replace('AndroidTest', 'HostTest').replace('Fixture.kt','HostFixture.kt')
    # Fixture class names must be unique across the source set.
    text=text.replace('FullFlowWireFixture', 'HostFullFlowWireFixture').replace('FullFlowProductionFixture', 'HostFullFlowProductionFixture')
    if args.check:
        assert dest.read_text()=='// Generated by scripts/mirror_golos_fullflow.py; edit Android source instead.\n'+text, f'mirror drift: {dest}'
    else: dest.write_text('// Generated by scripts/mirror_golos_fullflow.py; edit Android source instead.\n'+text)
    if args.check: pass
print(f'{len(files)} Android sources considered; lifecycle intentionally device-only')
